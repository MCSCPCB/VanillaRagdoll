// Maintainer-only snapshot tool. CI and browsers consume the checked-in result;
// neither needs the installed game or the private .local/reference directory.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadResources } from '../../.local/scripts/resources.mjs';

const root = new URL('../../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const hash = text => createHash('sha256').update(text).digest('hex');
const baseline = JSON.parse(await read('.local/metadata/resource-baseline.json'));
if (baseline.version !== '1.26.50') throw Error('Review the vanilla baseline before updating the website snapshot');
const resources = await loadResources(), entities = JSON.parse(await read('.local/metadata/entities.json'));
const profiles = [], sources = {};
// These families require renderer/runtime contracts beyond a geometry reference.
// Keep their exclusion explicit instead of applying the ordinary-entity adapter.
const special = new Set(['player', 'ender_dragon', 'wither', 'slime', 'magma_cube', 'sulfur_cube', 'armadillo']);
for (const entity of entities) {
  const client = resources.clients.get(entity.id).value['minecraft:client_entity'].description;
  for (const profile of entity.profiles) {
    const source = await read(profile.file); sources[profile.file] = hash(source);
    profiles.push({ entity: entity.id, key: profile.key, alias: profile.geometry,
      geometry: client.geometry[profile.geometry], familyGeometry: client.geometry,
      folded: !!profile.folded, special: special.has(entity.id.slice(10)), config: JSON.parse(source) });
  }
}
const geometryIds = new Set(profiles.map(p => p.geometry));
const catalog = { version: baseline.version, profiles,
  geometries: Object.fromEntries([...resources.geometries].filter(([id]) => geometryIds.has(id))),
  animations: Object.fromEntries(resources.animations), controllers: Object.fromEntries(resources.controllers),
  renderers: Object.assign({}, ...[...resources.json.values()].map(v => v.render_controllers ?? {})) };
const dest = new URL('../src/generator/vanilla/', import.meta.url);
await mkdir(dest, { recursive: true });
const writeAdapter = (name, source) => writeFile(new URL(name + '.mjs', dest), source.replace(/\r\n/g, '\n').trimEnd() + '\n');
const snapshot = '// Generated by website/scripts/sync-vanilla.mjs; do not edit.\nexport default ' + JSON.stringify(catalog) + ';\n';
await writeFile(new URL('catalog.mjs', dest), snapshot);

const core = '../../../vendor/simple-ragdoll/src/core/';
const copies = ['base-pose', 'vanilla-animation-stack', 'pose-cache', 'pose-routing', 'decorations', 'cat-native'];
for (const name of copies) {
  const path = '.local/scripts/' + name + '.mjs', source = await read(path); sources[path] = hash(source);
  await writeAdapter(name, '// Snapshot of ' + path + '; see SOURCE.json.\n' + source.replaceAll('../../../Simple-Ragdoll/src/core/', core));
}
// Extract only the runtime adapters, not the filesystem-based rig editing tools.
for (const [name, start, end, imports] of [
  ['articulation', 'export function articulationRig', '\nasync function main', `import {A,If,axes,vector,copy,rotate as rotateNodes,add as addNodes,sub as subNodes,scale as scaleNodes} from '${core}expression.mjs';\n`],
  ['gameplay-fixes', 'export function bigHeadFactor', null, `import {boneOutput} from '${core}program.mjs';\nimport {A,If,axes} from '${core}expression.mjs';\nimport {activeVanillaIds} from './vanilla-animation-stack.mjs';\n`],
  ['contact-performance', 'export function coreTerrainOnly', '\n  if(entity.id!==', `import {If} from '${core}expression.mjs';\n`],
]) {
  const path = '.local/scripts/' + name + '.mjs', source = await read(path); sources[path] = hash(source);
  const a = source.indexOf(start), b = end ? source.indexOf(end, a) : source.length;
  if (a < 0 || b < a) throw Error('Adapter source changed: ' + path);
  const tail = name === 'contact-performance' ? '\n  return program;\n}\n' : '';
  await writeAdapter(name, '// Runtime adapter extracted from ' + path + '; see SOURCE.json.\n' + imports + source.slice(a, b) + tail);
}
await writeFile(new URL('SOURCE.json', dest), JSON.stringify({ baseline: baseline.version,
  description: 'Pinned vanilla geometry and animation metadata for compilation only. Geometry is never emitted into patches. Physics configurations and runtime adapters are maintained by VanillaRagdoll.',
  catalogSha256: hash(snapshot), sources }, null, 2) + '\n');
console.log(JSON.stringify({ profiles: profiles.length, geometries: geometryIds.size, bytes: Buffer.byteLength(snapshot) }));
